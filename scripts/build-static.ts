#!/usr/bin/env node
/**
 * Build `docs/demo/` - the static, client-side demo.
 *
 * Three steps, all reproducible:
 *   1. inline the sample copybooks and data files as base64 + the guarantee strip from
 *      `docs/guarantees.md`, into `src/static/samples.generated.ts` (committed, because the
 *      bundle imports it);
 *   2. bundle `src/static/app.ts` with esbuild for the browser, aliasing `node:crypto` to the
 *      tested SHA-256 shim (COMP-3 files must hash exactly as they do in Node);
 *   3. write `docs/demo/index.html` from `renderStaticPage()`.
 *
 * After it runs, `docs/demo/` holds two files and no server: open index.html and everything
 * happens in the tab.
 */
import { build } from 'esbuild';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderStaticPage } from '../src/static/page.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outDir = join(root, 'docs', 'demo');

function base64(path: string): string {
  return readFileSync(path).toString('base64');
}

function samples(): { copybooks: unknown[]; data: unknown[] } {
  const copybookDir = join(root, 'samples', 'copybooks');
  const dataDir = join(root, 'samples', 'data');
  return {
    copybooks: readdirSync(copybookDir)
      .filter((name) => name.endsWith('.cpy'))
      .sort()
      .map((name) => ({ name, base64: base64(join(copybookDir, name)), bytes: readFileSync(join(copybookDir, name)).length })),
    data: readdirSync(dataDir)
      .filter((name) => name.endsWith('.txt'))
      .sort()
      .map((name) => ({ name, base64: base64(join(dataDir, name)), bytes: readFileSync(join(dataDir, name)).length })),
  };
}

/** The same numbered-list parse `src/core/guarantees.ts` performs, minus `node:fs`. */
function guarantees(): { guaranteed: string[]; notGuaranteed: string[]; sourcePath: string } {
  const text = readFileSync(join(root, 'docs', 'guarantees.md'), 'utf8');
  const guaranteed: string[] = [];
  const notGuaranteed: string[] = [];
  let section: 'none' | 'yes' | 'no' = 'none';
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (/^##\s+Guaranteed/i.test(line)) {
      section = 'yes';
      continue;
    }
    if (/^##\s+Not guaranteed/i.test(line)) {
      section = 'no';
      continue;
    }
    if (/^##\s/.test(line)) {
      section = 'none';
      continue;
    }
    const item = /^\d+\.\s+(.+)$/.exec(line);
    if (!item || section === 'none') continue;
    const entry = item[1]!.replace(/\*\*/g, '').replace(/`/g, '').trim();
    if (section === 'yes') guaranteed.push(entry);
    else notGuaranteed.push(entry);
  }
  return { guaranteed, notGuaranteed, sourcePath: 'docs/guarantees.md' };
}

function writeSamplesModule(): void {
  const { copybooks, data } = samples();
  const body = `/**
 * GENERATED by scripts/build-static.ts - do not edit.
 *
 * The demo ships its samples inside the bundle so that opening index.html needs no server and
 * makes no request. Regenerate with \`npm run build:static\`.
 */
export interface SampleFile {
  name: string;
  base64: string;
  bytes: number;
}

export const COPYBOOKS: SampleFile[] = ${JSON.stringify(copybooks, null, 2)};

export const DATA: SampleFile[] = ${JSON.stringify(data, null, 2)};

export const GUARANTEES = ${JSON.stringify(guarantees(), null, 2)};
`;
  writeFileSync(join(root, 'src', 'static', 'samples.generated.ts'), body);
}

async function main(): Promise<void> {
  writeSamplesModule();
  mkdirSync(outDir, { recursive: true });

  const result = await build({
    entryPoints: [join(root, 'src', 'static', 'app.ts')],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: ['es2020'],
    outfile: join(outDir, 'bundle.js'),
    alias: { 'node:crypto': join(root, 'src', 'static', 'sha256-browser.ts') },
    legalComments: 'none',
    logLevel: 'info',
  });
  if (result.errors.length > 0) process.exitCode = 1;

  writeFileSync(join(outDir, 'index.html'), renderStaticPage());
  const bundle = readFileSync(join(outDir, 'bundle.js'), 'utf8');
  console.log(`docs/demo/bundle.js  ${(bundle.length / 1024).toFixed(1)} KB`);
  console.log(`docs/demo/index.html ${(renderStaticPage().length / 1024).toFixed(1)} KB`);
  if (/from ['"]node:/.test(bundle) || /require\(['"]node:/.test(bundle)) {
    console.error('bundle still references a node: module - the demo would fail in a browser');
    process.exitCode = 1;
  }
}

await main();
